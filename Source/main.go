package main

import (
	"crypto/tls"
	"flag"
	"fmt"
	"log"
	"net"
	"net/http"
	"os"
	"os/signal"
	"path/filepath"
	"strconv"
	"strings"
	"syscall"
	"time"
)

func main() {
	if len(os.Args) > 1 && strings.HasPrefix(os.Args[1], "everythingsearch:") {
		handleProtocolActivation(os.Args[1])
		return
	}

	flag.Parse()

	if p := os.Getenv("EVERYTHING_PORT"); p != "" {
		if v, err := strconv.Atoi(p); err == nil && v > 0 && v < 65536 {
			serverPort = v
		}
	}

	// Log to file so MSIX startup task output is visible.
	// We use a custom tail log writer to keep the log file size to around 500 lines.
	os.MkdirAll(certDir(), 0700)
	logPath := filepath.Join(certDir(), "server.log")

	rw, err := newTailLogWriter(logPath, 1000, 500)
	if err == nil {
		log.SetOutput(rw)
		defer rw.Close()
	} else {
		// Fallback to standard file if rotating logger fails
		f, err := os.OpenFile(logPath, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
		if err == nil {
			log.SetOutput(f)
			defer f.Close()
		}
	}
	log.Printf("=== Server starting (PID %d) — log file: %s ===", os.Getpid(), logPath)

	// Verify TLS certificate files exist (generated by cert\setup-cert.ps1).
	if _, err := os.Stat(certFile()); os.IsNotExist(err) {
		log.Fatalf("TLS certificate missing (%s). Please run cert\\setup-cert.ps1 to generate and trust the certificate.", certFile())
	}
	if _, err := os.Stat(keyFile()); os.IsNotExist(err) {
		log.Fatalf("TLS private key missing (%s). Please run cert\\setup-cert.ps1 to generate and trust the certificate.", keyFile())
	}
	log.Println("TLS certificate found.")

	// Verify that Everything CLI is reachable.
	if path := findEsExe(); path != "" {
		log.Printf("Found Everything CLI at: %s", path)
	} else {
		log.Fatal("es.exe not found. Install VoidTools Everything and ensure es.exe is in PATH or in the default install directory.")
	}

	// Prevent multiple instances — check if port is already in use.
	addr := fmt.Sprintf("localhost:%d", serverPort)
	ln, err := net.Listen("tcp", addr)
	if err != nil {
		log.Fatalf("Port %d is already in use — is another instance running?", serverPort)
	}
	ln.Close()

	// Build HTTP server.
	mux := http.NewServeMux()
	mux.HandleFunc("/api/search", withCORS(handleSearch))
	mux.HandleFunc("/api/preview", withCORS(handlePreview))
	mux.HandleFunc("/api/open", withCORS(handleOpen))
	mux.HandleFunc("/api/file", withCORS(handleFile))

	tlsCert, err := tls.LoadX509KeyPair(certFile(), keyFile())
	if err != nil {
		log.Fatalf("failed to load TLS keypair: %v", err)
	}

	srv := &http.Server{
		Addr:    addr,
		Handler: mux,
		TLSConfig: &tls.Config{
			Certificates: []tls.Certificate{tlsCert},
			MinVersion:   tls.VersionTLS12,
		},
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       10 * time.Second,
		WriteTimeout:      10 * time.Second,
		IdleTimeout:       60 * time.Second,
		MaxHeaderBytes:    16 << 10,
	}

	log.Printf("Everything Search Provider listening on https://%s", addr)
	log.Println("Press Ctrl+C to stop.")

	// Graceful shutdown on Ctrl+C.
	quit := make(chan os.Signal, 1)
	signal.Notify(quit, syscall.SIGINT, syscall.SIGTERM)
	go func() {
		<-quit
		log.Println("Shutting down …")
		srv.Close()
	}()

	if err := srv.ListenAndServeTLS("", ""); err != http.ErrServerClosed {
		log.Fatalf("server error: %v", err)
	}
	log.Println("Server stopped.")
}

<#
.SYNOPSIS
    Builds the Go binary, packages it into an MSIX, and signs it.

.DESCRIPTION
    Prerequisites:
      - Go 1.21+
      - Windows SDK (for MakeAppx.exe and SignTool.exe)
      - Assets\StoreLogo.png (150x150 recommended)

    Run from the project root directory.

    CERTIFICATES (two separate certs, don't confuse them):

      TLS certificate  (cert.pem / key.pem / root.cer)
        - Generated and trusted by cert\setup-cert.ps1.
        - Used for HTTPS between Windows Search and the local server.
        - Stays valid for 5 years — stored in %LOCALAPPDATA%\EverythingSearchProvider.

      MSIX signing certificate  (_signing.pfx / _signing.cer)
        - Auto-generated by this script on first build, stored in the project dir.
        - Used to sign the MSIX package so Windows accepts the sideloaded app.
        - Trusted via cert\setup-cert.ps1 (imports into LocalMachine\TrustedPeople).
        - Stays valid for 5 years — never regenerated unless you delete _signing.pfx.

#>

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

$AppName      = "EverythingSearch"
$SigningPfx   = "_signing.pfx"
$SigningCer	  = "_signing.cer"
$SigningPass  = "everything_search"

# ---------------------------------------------------------------------------
# Locate Windows SDK tools
# ---------------------------------------------------------------------------

$MakeAppx = $null
$SignTool = $null
$MakePri  = $null

$sdkRoots = @(
    "${env:ProgramFiles(x86)}\Windows Kits\10\bin",
    "$env:ProgramFiles\Windows Kits\10\bin"
)

foreach ($root in $sdkRoots) {
    if (Test-Path $root) {
        $versions = Get-ChildItem $root -Directory | Where-Object { $_.Name -match '^\d+\.' } | Sort-Object Name -Descending
        foreach ($ver in $versions) {
            $arch = if ([Environment]::Is64BitOperatingSystem) { "x64" } else { "x86" }
            $ma = Join-Path $ver.FullName "$arch\MakeAppx.exe"
            $st = Join-Path $ver.FullName "$arch\SignTool.exe"
            $mp = Join-Path $ver.FullName "$arch\MakePri.exe"
            if (Test-Path $ma) { $MakeAppx = $ma }
            if (Test-Path $st) { $SignTool = $st }
            if (Test-Path $mp) { $MakePri = $mp }
            if ($MakeAppx -and $SignTool -and $MakePri) { break }
        }
    }
    if ($MakeAppx -and $SignTool -and $MakePri) { break }
}

if (-not $MakeAppx -or -not $SignTool -or -not $MakePri) {
    Write-Host ""
    Write-Host "  Windows SDK tools not found (MakeAppx, SignTool, MakePri)." -ForegroundColor Red
    Write-Host "  Install the Windows SDK from:" -ForegroundColor Yellow
    Write-Host "  https://developer.microsoft.com/en-us/windows/downloads/windows-sdk/" -ForegroundColor Cyan
    Write-Host ""
    exit 1
}

Write-Host ""
Write-Host "  MakeAppx: $MakeAppx" -ForegroundColor DarkGray
Write-Host "  SignTool: $SignTool" -ForegroundColor DarkGray
Write-Host "  MakePri:  $MakePri" -ForegroundColor DarkGray

# ---------------------------------------------------------------------------
# 1. Build the Go binary
# ---------------------------------------------------------------------------

Write-Host ""
Write-Host "  [1/4] Building Go binary ..." -ForegroundColor Cyan

$outputDir = "Output"
if (-not (Test-Path $outputDir)) { New-Item -ItemType Directory -Path $outputDir -Force | Out-Null }
$exeOutput = Join-Path $outputDir "$AppName.exe"

go build -ldflags="-s -w -H windowsgui" -o $exeOutput .\Source
if ($LASTEXITCODE -ne 0) {
    Write-Host "  go build failed." -ForegroundColor Red
    exit 1
}
Write-Host "  -> $exeOutput built successfully." -ForegroundColor Green

# ---------------------------------------------------------------------------
# 2. Stage the package content
# ---------------------------------------------------------------------------

Write-Host ""
Write-Host "  [2/4] Staging package content ..." -ForegroundColor Cyan

$staging = "_staging"
if (Test-Path $staging) { Remove-Item $staging -Recurse -Force }
New-Item -ItemType Directory -Path $staging -Force | Out-Null

Copy-Item $exeOutput "$staging\"
Copy-Item "AppxManifest.xml" "$staging\"

# Assets
if (Test-Path "Assets\StoreLogo.png") {
    New-Item -ItemType Directory -Path "$staging\Assets" -Force | Out-Null
    Copy-Item "Assets\StoreLogo.png" "$staging\Assets\"
} else {
    Write-Host "  [!] Assets\StoreLogo.png not found – package may not render icons." -ForegroundColor Yellow
}

# Everything CLI
if (Test-Path "Output\es.exe") {
    Copy-Item "Output\es.exe" "$staging\"
} elseif (Test-Path "es.exe") {
    Copy-Item "es.exe" "$staging\"
}

if (Test-Path "Output\Everything_License.txt") {
    Copy-Item "Output\Everything_License.txt" "$staging\"
} elseif (Test-Path "Everything_License.txt") {
    Copy-Item "Everything_License.txt" "$staging\"
}

# Public folder (required by uap3:AppExtension PublicFolder attribute)
# Must contain at least one file — MakeAppx skips empty directories.
New-Item -ItemType Directory -Path "$staging\Public" -Force | Out-Null
Set-Content -Path "$staging\Public\.placeholder" -Value "" -NoNewline

# Localization resources
if (Test-Path "Strings") {
    Copy-Item "Strings" "$staging\Strings" -Recurse

    # Generate PRI config
    Write-Host "  Compiling PRI resources ..." -ForegroundColor DarkGray
    $priConfig = "priconfig.xml"
    & $MakePri createconfig /cf $priConfig /dq en-US /o | Out-Null

    # Remove <packaging> node to force all languages into a single resources.pri
    # rather than splitting them into resources.language-*.pri (which requires an msixbundle).
    [xml]$priXml = Get-Content $priConfig
    $packagingNode = $priXml.SelectSingleNode("//packaging")
    if ($packagingNode) {
        $packagingNode.ParentNode.RemoveChild($packagingNode) | Out-Null
    }
    $priXml.Save("$pwd\$priConfig")

    & $MakePri new /pr $staging /cf $priConfig /in EverythingSearchProvider /of "$staging\resources.pri" /o | Out-Null
    Remove-Item $priConfig -Force
}

# ---------------------------------------------------------------------------
# 3. Create MSIX
# ---------------------------------------------------------------------------

Write-Host ""
Write-Host "  [3/4] Creating MSIX package ..." -ForegroundColor Cyan

$msixFile = Join-Path $outputDir "$AppName.msix"
if (Test-Path $msixFile) { Remove-Item $msixFile -Force }

& $MakeAppx pack /d $staging /p $msixFile /o
if ($LASTEXITCODE -ne 0) {
    Write-Host "  MakeAppx pack failed." -ForegroundColor Red
    exit 1
}
Write-Host "  -> $msixFile created." -ForegroundColor Green

# ---------------------------------------------------------------------------
# 4. Sign the MSIX
# ---------------------------------------------------------------------------

Write-Host ""
Write-Host "  [4/4] Signing MSIX package ..." -ForegroundColor Cyan

# Create signing PFX on first build, reuse on subsequent builds.
$signCert = $null
if (-not (Test-Path $SigningPfx)) {
    Write-Host "  Creating new signing certificate ..." -ForegroundColor DarkGray
    $signCert = New-SelfSignedCertificate `
        -Type CodeSigningCert `
        -Subject "CN=${AppName}_LocalDev_DO_NOT_TRUST" `
        -CertStoreLocation "Cert:\CurrentUser\My" `
        -KeyAlgorithm RSA `
        -KeyLength 4096 `
        -HashAlgorithm SHA256 `
        -KeyExportPolicy Exportable `
        -NotAfter (Get-Date).AddYears(5)

    $securePass = ConvertTo-SecureString $SigningPass -Force -AsPlainText
    Export-PfxCertificate -Cert $signCert -FilePath $SigningPfx -Password $securePass | Out-Null

    # Export only the public certificate for safe trusting
    Export-Certificate -Cert $signCert -FilePath "$SigningCer" | Out-Null

    # Delete the certificate from CurrentUser\My to prevent private key exposure
    Remove-Item -Path "Cert:\CurrentUser\My\$($signCert.Thumbprint)" -Force

    Write-Host "  -> Signing certificate saved to $SigningPfx and $SigningCer ." -ForegroundColor Green
} else {
    Write-Host "  Reusing existing signing certificate ($SigningPfx)." -ForegroundColor DarkGray
}

# Trust the signing certificate in LocalMachine\TrustedPeople.
# MSIX deployment requires the signing cert to be in this store.
# If not admin, this step is skipped — run the command below to trust manually.

if ($signCert) {
    try {
        $publicCert = New-Object System.Security.Cryptography.X509Certificates.X509Certificate2("$SigningCer")
        $tpStore = New-Object System.Security.Cryptography.X509Certificates.X509Store("TrustedPeople", "LocalMachine")
        $tpStore.Open("ReadWrite")
        $tpStore.Add($publicCert)
        $tpStore.Close()
        Write-Host "  -> Signing certificate trusted (LocalMachine\TrustedPeople)." -ForegroundColor Green
    } catch {
        Write-Host "  [!] Could not trust signing cert in LocalMachine\TrustedPeople." -ForegroundColor Yellow
        Write-Host "      Run this command as Administrator to trust it:" -ForegroundColor Yellow
        Write-Host "      Import-Certificate -FilePath ""$SigningCer"" -CertStoreLocation Cert:\LocalMachine\TrustedPeople" -ForegroundColor White
    }
} else {
    # If reusing existing PFX, try importing the public .cer to the store
    try {
        if (-not (Test-Path "$SigningCer")) {
            $tempCert = New-Object System.Security.Cryptography.X509Certificates.X509Certificate2($SigningPfx, $SigningPass)
            [System.IO.File]::WriteAllBytes("$pwd\$SigningCer", $tempCert.Export([System.Security.Cryptography.X509Certificates.X509ContentType]::Cert))
        }
        Import-Certificate -FilePath "$SigningCer" -CertStoreLocation Cert:\LocalMachine\TrustedPeople | Out-Null
        Write-Host "  -> Signing certificate trusted (LocalMachine\TrustedPeople)." -ForegroundColor Green
    } catch {
        Write-Host "  [!] MSIX install may fail — signing cert not in LocalMachine\TrustedPeople." -ForegroundColor Yellow
        Write-Host "      Re-run build.ps1 as Administrator, or run:" -ForegroundColor Yellow
        Write-Host "      Import-Certificate -FilePath ""$SigningCer"" -CertStoreLocation Cert:\LocalMachine\TrustedPeople" -ForegroundColor White
    }
}

# Sign the MSIX using the PFX file
$signResult = & $SignTool sign /fd SHA256 /f $SigningPfx /p $SigningPass /a $msixFile 2>&1
if ($LASTEXITCODE -ne 0) {
    Write-Host "  SignTool failed:" -ForegroundColor Yellow
    $signResult | ForEach-Object { Write-Host "    $_" -ForegroundColor DarkGray }
    Write-Host "  The MSIX was NOT signed. Developer Mode still allows installation via:" -ForegroundColor Yellow
    Write-Host "    Add-AppxPackage -Path $msixFile" -ForegroundColor White
} else {
    Write-Host "  -> $msixFile signed." -ForegroundColor Green
}

# Cleanup staging
Remove-Item $staging -Recurse -Force -ErrorAction SilentlyContinue

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------

Write-Host ""
Write-Host "  ===============================================" -ForegroundColor Cyan
Write-Host "  Build complete!" -ForegroundColor Green
Write-Host "  ===============================================" -ForegroundColor Cyan
Write-Host ""
Write-Host "  Output:  $msixFile" -ForegroundColor White
Write-Host ""
Write-Host "  ONE-TIME SETUP STEPS (run once, then done):" -ForegroundColor Yellow
Write-Host "    pwsh -NoProfile -File cert\setup-cert.ps1" -ForegroundColor White
Write-Host "    (or double-click cert\setup.bat)" -ForegroundColor DarkGray
Write-Host ""
Write-Host "  To install:" -ForegroundColor Yellow
Write-Host "    1. Make sure Developer Mode is ON:" -ForegroundColor White
Write-Host "       Settings > System > For developers > Developer Mode" -ForegroundColor White
Write-Host "    2. Double-click $msixFile to install" -ForegroundColor White
Write-Host "    3. Launch EverythingSearch.exe (or reboot for auto-start)" -ForegroundColor White
Write-Host "    4. Enable the provider in Windows Search" -ForegroundColor White
Write-Host "       Settings > Search permissions > Search providers" -ForegroundColor White
Write-Host ""
